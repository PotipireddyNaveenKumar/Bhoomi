@pytest.mark.asyncio
async def test_llm_factory_resolution():
    """Verify that factory respects LLM_PROVIDER and falls back safely to Mock."""
    # 1. Default / Mock
    provider = get_llm_provider("mock")
    assert isinstance(provider, MockLLMProvider)

    # 2. OpenAI provider creation
    os.environ["OPENAI_API_KEY"] = "sk-test-mock-key-12345"
    provider_openai = get_llm_provider("openai")
    assert isinstance(provider_openai, OpenAIProvider)
    assert provider_openai.model == "gpt-4o-mini"
    assert provider_openai.provider_name == "openai"

    # 3. Groq provider creation
    os.environ["GROQ_API_KEY"] = "gsk-test-mock-groq-key-12345"
    provider_groq = get_llm_provider("groq")
    assert isinstance(provider_groq, OpenAIProvider)
    assert provider_groq.provider_name == "groq"
    assert "groq.com" in provider_groq.base_url

    # 4. Gemini provider creation
    os.environ["GEMINI_API_KEY"] = "gemini-test-mock-key-12345"
    provider_gemini = get_llm_provider("gemini")
    assert isinstance(provider_gemini, GeminiProvider)

    # 5. Clean up test env keys
    os.environ.pop("OPENAI_API_KEY", None)
    os.environ.pop("GROQ_API_KEY", None)
    os.environ.pop("GEMINI_API_KEY", None)

