@pytest.mark.asyncio
async def test_real_llm_graceful_fallback_on_network_error():
    """Verify that network/auth failure does NOT crash the platform; falls back to Mock."""
    # Use invalid key and bad URL to force network error
    failing_provider = OpenAIProvider(api_key="invalid-key", base_url="https://invalid.endpoint.test", timeout=1.0)
    messages = [{"role": "user", "content": "What is the market price of chilli?"}]
    
    resp = await failing_provider.generate_response(messages=messages, system_prompt="Test")
    assert resp is not None
    assert resp.provider == "mock"
    assert "mandi" in resp.content.lower() or "price" in resp.content.lower() or "noted" in resp.content.lower()

@pytest.mark.asyncio
async def test_orchestrator_five_step_tool_loop():
    """
    Verify complete 5-step loop:
    1. Intent detection
    2. Tool selection
    3. Structured argument passing
    4. Deterministic tool execution
    5. SafetyEngine verification
    """
    result = await BhoomiAgentOrchestrator.process_turn(
        farmer_id="farmer_test_turn",
        user_text="What is my expected profit if I cultivate 3 acres of Chilli yielding 10 quintals at 12000 per quintal?"
    )
    
    assert result.response_text is not None
    assert len(result.response_text) > 20
    # Verify deterministic profit card was generated by tool execution
    assert len(result.visual_cards) > 0
    profit_cards = [c for c in result.visual_cards if c.get("card_type") in ["profit_card", "PROFIT_SUMMARY"]]
    assert len(profit_cards) == 1
    # Check that safety engine ran without crashing
    assert "⚠️" not in result.response_text or "Warning" in result.response_text

@pytest.mark.asyncio
async def test_safety_engine_blocks_unsafe_chemicals_in_orchestrator():
    """Verify that SafetyEngine strictly overrides any unsafe LLM advice."""
    unsafe_text = "I recommend spraying Monocrotophos on your chilli plants to control thrips."
    evaluation = SafetyEngine.evaluate(unsafe_text)
    assert evaluation.is_safe is False
    assert evaluation.status == "BLOCK"
    assert any("Monocrotophos" in r and "restricted/banned" in r for r in evaluation.blocked_reasons)
    assert "Safety Alert" in evaluation.modified_text
